// ===========================================================================
// winmon.h —— 显示器与 DPI（声明）
//
// ⚠️ 为什么它不再是 header-only 了
// ---------------------------------------------------------------------------
// 原来这个头里所有函数和变量都是 static。那在"一个 exe 配一个 cpp"时没问题，
// 但本项目的 server 有多个 cpp 都包含它 —— 于是【每个编译单元各拿到一份副本】。
// 现象：ActionsInit() 在 act_state.cpp 里填了 2 台显示器，
//       而 server.cpp 读自己那份，还是 0。
//
// 所以改成 .h 声明 + winmon.cpp 定义的常规写法。凡是"要被多个 cpp 共享"的
// 状态，都不能放在 header-only 的 static 里。
// ===========================================================================

#ifndef WINMON_H
#define WINMON_H

#include <windows.h>

// ---------------------------------------------------------------------------
// 本项目的坐标约定
// ---------------------------------------------------------------------------
// 对外一律使用【某个显示器内的局部坐标】（左上角为 0,0），不使用整体虚拟屏幕
// 坐标 —— 这样就没有负原点和"黑洞区"的麻烦。
// 唯一的例外是 get_state 里的 clip_screen，它天生是屏幕空间的。
//
// 需要屏幕坐标时： localToScreen = mon.rc.left + localX
// ---------------------------------------------------------------------------

#define WM_MAX_MONITORS 16

// 一台显示器的信息
struct WmMon {
    HMONITOR hmon;
    RECT     rc;         // 物理像素；屏幕坐标（多屏时可能有负值）
    RECT     work;       // 工作区 = rc 扣掉任务栏
    int      primary;
    UINT     dpiX, dpiY; // 通常 96 / 120 / 144
    WCHAR    device[64]; // 例如 \\.\DISPLAY1
};

// ---------------------------------------------------------------------------
// 全局显示器状态（唯一定义在 winmon.cpp）
// ---------------------------------------------------------------------------
extern WmMon   g_wmMon[WM_MAX_MONITORS];
extern int     g_wmMonCount;

// ---------------------------------------------------------------------------
// ★ 每个操作屏幕的程序都要先调它
//
// 必须早于任何 GDI / 窗口 / 屏幕相关的调用。做过之后 Windows 才会把物理像素
// 原样给你。返回实际生效的模式名，供打印核对。
// ---------------------------------------------------------------------------
const char* WmEnablePerMonitorV2(void);

// 每次运行都要重新调用 —— 显示器拓扑随时会变（拔屏 / Win+P / 显示器休眠掉线）
void WmLoadMonitors(void);

// 屏幕坐标 -> 显示器下标；-1 = 不在任何显示器上
int WmMonitorFromPoint(POINT pt);

// 局部坐标校验：合法返回显示器下标，非法返回 -1
int WmMonitorFromLocal(int monIndex, int localX, int localY);

// 局部坐标 -> 屏幕坐标
POINT WmLocalToScreen(int monIndex, int localX, int localY);

#endif // WINMON_H
